import csv
import json
import buyer_intel as bi
from openpyxl import Workbook, load_workbook
from vve import tradedata
from vve.jobs import merge_save


ROWS = [
    ["Date", "Importer Name", "Importer Country", "Exporter Name", "Country of Origin", "HS Code", "Product Description", "Quantity", "Unit", "Value USD"],
    ["12/03/2026", "Gulf Spice Trading LLC", "United Arab Emirates", "Erode Exports", "India", "09103020", "DRIED TURMERIC FINGERS POLISHED", "25000", "KGS", "38000"],
    ["02/05/2026", "Gulf Spice Trading LLC", "United Arab Emirates", "Erode Exports", "India", "09103020", "TURMERIC FINGER", "26000", "KGS", "39000"],
    ["20/06/2026", "Desert Foods FZE", "United Arab Emirates", "Kerala Agro", "India", "091030", "TURMERIC", "10000", "KGS", "15000"],
    ["21/06/2026", "Nut House LLC", "United Arab Emirates", "Cashew Co", "Vietnam", "080132", "CASHEW KERNELS W320", "15876", "KGS", "110000"],
    ["", "", "", "", "", "", "", "", "", ""],
]


def write_csv(p):
    with open(p, "w", newline="") as f:
        csv.writer(f).writerows(ROWS)


def write_xlsx(p):
    wb = Workbook()
    ws = wb.active
    ws.append(["Volza export - generated by user"])   # title row above the header
    for r in ROWS:
        ws.append(r)
    wb.save(p)


def check(res):
    cs = {c["name"]: c for c in res["companies"]}
    gulf = {p["product"]: p for p in cs["Gulf Spice Trading LLC"]["products"]}
    assert set(gulf) == {"turmeric_fingers"}, "fingers shipments must not create a powder record"
    f = gulf["turmeric_fingers"]
    assert f["evidence"] == "shipment" and f["form_evidence"] == "shipment_description"
    assert f["shipment_count"] == 2 and f["last_shipment_date"] == "2026-05-02" and "51,000.0 KGS" in f["shipment_volume"]
    assert f["sources_from_india"] is True and f["supplier_countries"] == "India"
    desert = {p["product"]: p for p in cs["Desert Foods FZE"]["products"]}
    assert set(desert) == {"turmeric_powder", "turmeric_fingers"}
    assert all(p["evidence"] == "shipment_form_unknown" for p in desert.values())
    nut = cs["Nut House LLC"]["products"][0]
    assert nut["product"] == "cashew_kernels" and "W320" in nut["grades"] and nut["sources_from_india"] is None


def test_csv_import(tmp_path):
    p = tmp_path / "volza.csv"
    write_csv(p)
    res = tradedata.import_shipments(p, "volza", research_date="2026-11-10")
    assert res["rows"] == 5 and res["skipped"] == 1
    check(res)


def test_xlsx_import_with_title_row(tmp_path):
    p = tmp_path / "panjiva.xlsx"
    write_xlsx(p)
    check(tradedata.import_shipments(p, "panjiva", research_date="2026-11-10"))


def test_import_rejects_unknown_source_and_missing_importer(tmp_path):
    import pytest
    p = tmp_path / "x.csv"
    p.write_text("a,b,c\n1,2,3\n")
    with pytest.raises(ValueError):
        tradedata.import_shipments(p, "un_comtrade")
    with pytest.raises(ValueError, match="importer"):
        tradedata.import_shipments(p, "volza")


def test_imported_shipments_score_and_classify(tmp_path):
    p = tmp_path / "v.csv"
    write_csv(p)
    res = tradedata.import_shipments(p, "volza", research_date="2026-11-10")
    merge_save(tmp_path, "United Arab Emirates", res["companies"])
    comps = bi.load_companies(tmp_path)
    gulf = next(c for c in comps if c.name.startswith("Gulf"))
    pr = gulf.products[0]
    assert bi.size_class(gulf, pr) == bi.SIZE_A        # volume known
    s = bi.score(gulf, pr)
    assert s["product_relevance"] == 25 and s["import_activity"] == 20 and s["target_market"] == 10
    assert s["business_verification"] == 0 and s["contact_availability"] == 0   # nothing verified yet


def test_report_generation(tmp_path):
    data = tmp_path / "data"
    data.mkdir()
    (data / "buyers_uae.json").write_text(json.dumps([
        {"company_id": "1", "name": "Spice Co LLC", "country": "United Arab Emirates", "website": "https://spice.ae/",
         "website_checked": True, "business_category": "importer", "independent_sources": ["https://gulfood.com/x"],
         "products": [{"product": "turmeric_powder", "evidence": "catalogue_exact", "form_evidence": "catalogue"},
                      {"product": "cashew_kernels", "evidence": "category_only"}]}]))
    (data / "country_rankings.json").write_text(json.dumps([{"product": "t", "hs": "091030", "rank": 1, "country": "USA",
                                                             "year": 2023, "import_value_usd_m": 50.8}]))
    out = tmp_path / "out"
    res = bi.build(data, out)
    assert res == {"companies": 1, "rows": 2, "lists": 2}
    assert (out / "consolidated_buyers.csv").exists()
    assert (out / "by_product_country" / "turmeric_powder__United_Arab_Emirates.csv").exists()
    wb = load_workbook(out / "VVE_Global_Buyer_Intelligence.xlsx")
    assert {"Summary", "Country ranking", "Turmeric Powder", "Cashew Kernels", "Companies (deduplicated)"} <= set(wb.sheetnames)
    rows = list(csv.DictReader(open(out / "consolidated_buyers.csv")))
    tp = next(r for r in rows if r["Product"] == "Turmeric Powder")
    assert tp["Verification status"] == "Verified" and tp["Product evidence level"] == "catalogue_exact"
